"""# **Part II - Viability**

## **Transfection**

To model the transfection step, we denote by

$$
T(s)
$$

the number of HEK cells effectively transfected by sequence $s$. We assume that

$$
T(s)\sim\mathrm{Poisson}\big(\rho\,\lambda_1(s)\big),
$$

where

- $\lambda_1(s)$ is the number of copies of sequence $s$ in the sampled pool;
- $\rho$ is the mean number of transfections per HEK cell.
"""

rho_exp=1.2*(10**(-4))
alpha_exp=4000

def number_tranfected_cells(Lambda, rho, stoch=True):
  """
  Parameters:
  Lambda : dict
      Dictionnary containing the number of sequences s in the amplified
  rho : float
      Mean number of transfections per HEK cell

  Returns:
  Lambda_prime : dict
      Dictionnary containing the number of cells
  """
  Lambda_prime={}
  for sequence,abundance in Lambda.items():
        mean_number=rho*abundance

        if stoch:
            number=np.random.poisson(mean_number)
        else:
            number=np.round(mean_number)

        Lambda_prime[sequence]=int(number)
  return Lambda_prime

