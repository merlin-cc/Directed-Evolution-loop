@contextmanager
def save_plots_in(cell_name, base_dir="Figures", dpi=300):
    """
    Sauvegarde automatiquement toutes les figures affichées par plt.show()
    dans un dossier propre à la cellule.
    """
    folder = Path(base_dir) / cell_name
    folder.mkdir(parents=True, exist_ok=True)

    old_show = plt.show
    counter = {"i": 1}

    def show_and_save(*args, **kwargs):
        fig_nums = plt.get_fignums()

        for num in fig_nums:
            fig = plt.figure(num)
            file_path = folder / f"figure_{counter['i']}.png"

            fig.savefig(file_path, dpi=dpi, bbox_inches="tight")
            counter["i"] += 1

        old_show(*args, **kwargs)

        # évite que les figures soient resauvegardées dans la cellule suivante
        plt.close("all")

    plt.show = show_and_save

    try:
        yield
    finally:
        plt.show = old_show

