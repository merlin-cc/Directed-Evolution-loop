def sequencing_approx(Lambda,D,phi=0.01):
  """
  Parameters:
  Lambda : dict
      Dictionnary containing the number of sequences s in the amplified
  D : int
      Sequencing depth
  Returns:
  Lambda_prime : dict
      Dictionnary containing the number of reads of sequence s
  """
  lambda_prime={}
  N=sum(Lambda.values())
  for sequence in Lambda.keys():
      qs=Lambda[sequence]/N
      mu_s=D*qs         # moyenne voulue
      phi=0.1           # dispersion choisie
      r=1/phi
      p=r/(r+mu_s)
      lambda_prime[sequence]=np.random.negative_binomial(int(r),p)
  return lambda_prime

