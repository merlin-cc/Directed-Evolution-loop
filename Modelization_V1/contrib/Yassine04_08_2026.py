"""## **Sampling**

Given ((\lambda_0(s))_s), we can simulate the sampling step by denoting by (N_1 < N_0) the number of sequences that are sampled.

We then have

$$
(\lambda_1(s))_s \sim \mathrm{Multinomial}\left(
N_1,
\left(
\frac{\lambda_0(s)}
{\sum\limits_{s'} \lambda_0(s')}
\right)_s
\right).
$$

"""

def sample_sequences(Lambda,N_1,stoch=True):
    """
    Parameters:
    Lambda : dict
        Dictionnary containing the number of sequences s from the mix we sample from
    N_1 : int
        Number of sequences we sample

    Returns:
    Lambda_prime : dict
        Dictionnary containing the number of sequences s in the sampled mix
    """
    sequences=list(Lambda.keys())
    counts=np.array(list(Lambda.values()),dtype=float)

    normalisator=counts.sum()

    if normalisator==0:
        return {sequence:0 for sequence in sequences}

    probabilities=counts/normalisator

    if stoch:
        sampled_counts=np.random.multinomial(N_1,probabilities)
    else:
        sampled_counts=np.round(probabilities*N_1)
        sampled_counts=sampled_counts.astype(int)

    Lambda_prime={
        sequences[i]:sampled_counts[i]
        for i in range(len(sequences))
    }

    return Lambda_prime

