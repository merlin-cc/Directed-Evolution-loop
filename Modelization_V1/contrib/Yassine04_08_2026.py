"""# **Part VI - Bacterial amplification**"""

def init_bact_ampl(Lambda,tau,stoch=True):
  """
  Parameters:
  Lambda : dict
    dictionnary containing all the sequences in the initial pool
  tau : float
    efficiency of the infection of a bacteria
  Return :
  Lambda_prime : dict
    dictionnary containing all the sequences in the final pool
  """
  if stoch :
    return {sequence: np.random.binomial(int(count), tau) for sequence, count in Lambda.items()}
  else :
    return {sequence: int(count*tau) for sequence, count in Lambda.items()}

def bacterial_amplification(Lambda,p_div,n,G,stoch=True):
  """
  Parameters:
  Lambda : dict
    dictionnary containing all the sequences in the initial pool
  p_div : float
    probability of bacterial division
  n : int
    current number of bacterial amplifications
  G : int
    number of bacterial amplifications
  Return :
  Lambda_prime : dict
    dictionnary containing all the sequences in the final pool

  """
  if n==G:
    return Lambda
  else :
    Lambda_prime=Lambda.copy()
    for sequence in Lambda.keys():
      if stoch :
        Lambda_prime[sequence]+=np.random.binomial(Lambda[sequence],p_div)
      else :
        Lambda_prime[sequence]+=int(Lambda[sequence]*p_div)
    return bacterial_amplification(Lambda_prime,p_div,n+1,G,stoch)

