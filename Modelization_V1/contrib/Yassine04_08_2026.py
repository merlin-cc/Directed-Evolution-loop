"""## Sequencing

After the PCR step, let

$$
q_s=\frac{X_s^{(M)}}{\sum_{s'} X_{s'}^{(M)}}
$$

be the proportion of sequence $s$ in the pool just before sequencing.

We denote by $D$ the sequencing depth, i.e. the total number of reads produced by the sequencer. The vector of read counts

$$
(\lambda(s))_s
$$

is then modeled by a multinomial distribution:

$$
(\lambda(s))_s \sim
\mathrm{Multinomial}\!\left(
D,\,(q_s)_s
\right).
$$


"""

def sequencing(Lambda,D):
    normalisation=sum(Lambda.values())

    if normalisation==0:
        return {sequence:0 for sequence in Lambda.keys()}

    qs={}
    for sequence in Lambda.keys():
        qs[sequence]=Lambda[sequence]/normalisation

    frequencies=np.array(list(qs.values()),dtype=float)
    sequences=list(qs.keys())

    number_of_reads=np.random.multinomial(D,frequencies)

    Lambda_prime={
        sequences[i]:number_of_reads[i]
        for i in range(len(sequences))
    }

    return Lambda_prime

