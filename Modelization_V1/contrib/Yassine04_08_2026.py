def evaluate_selection_ranking(Lambda0,Lambda1,F1,J1,F2,J2,T1,T2,k=10):
    if not isinstance(Lambda0,dict):
        raise TypeError("Lambda0 must be a dictionary.")
    if not isinstance(Lambda1,dict):
        raise TypeError("Lambda1 must be a dictionary.")
    if len(Lambda0)==0:
        raise ValueError("Lambda0 is empty.")
    if set(Lambda0.keys())!=set(Lambda1.keys()):
        raise ValueError("Lambda0 and Lambda1 must contain the same sequences.")
    if T1<=0 or T2<=0:
        raise ValueError("T1 and T2 must be strictly positive.")
    if k<1:
        raise ValueError("k must be strictly positive.")

    sequences=list(Lambda0.keys())
    combined_scores=np.array([fonction_score(sequence,F1,J1)/T1+fonction_score(sequence,F2,J2)/T2 for sequence in sequences],dtype=float)
    initial_abundances=np.array([Lambda0[sequence] for sequence in sequences],dtype=float)
    final_abundances=np.array([Lambda1[sequence] for sequence in sequences],dtype=float)

    if not np.all(np.isfinite(combined_scores)):
        raise ValueError("Some combined scores are not finite.")
    if not np.all(np.isfinite(initial_abundances)):
        raise ValueError("Some initial abundances are not finite.")
    if not np.all(np.isfinite(final_abundances)):
        raise ValueError("Some final abundances are not finite.")

    initially_present_indices=np.flatnonzero(initial_abundances>0)
    if len(initially_present_indices)==0:
        raise ValueError("No sequence is initially present.")

    k=min(k,len(initially_present_indices))
    score_order=initially_present_indices[np.argsort(-combined_scores[initially_present_indices],kind="stable")]
    top_k_indices=score_order[:k]
    top_k_sequences=[sequences[index] for index in top_k_indices]
    top_k_scores=combined_scores[top_k_indices]
    top_k_abundances=final_abundances[top_k_indices]

    scores_are_constant=np.all(top_k_scores==top_k_scores[0])
    abundances_are_constant=np.all(top_k_abundances==top_k_abundances[0])

    if scores_are_constant or abundances_are_constant:
        kendall_tau=np.nan
        spearman_rho=np.nan
    else:
        kendall_tau=kendalltau(top_k_scores,top_k_abundances,variant="b").statistic
        spearman_rho=spearmanr(top_k_scores,top_k_abundances).statistic

    number_of_inversions=0
    number_of_comparable_pairs=0
    number_of_tied_pairs=0

    for i in range(k):
        for j in range(i+1,k):
            score_difference=top_k_scores[i]-top_k_scores[j]
            abundance_difference=top_k_abundances[i]-top_k_abundances[j]
            if score_difference==0 or abundance_difference==0:
                number_of_tied_pairs+=1
                continue
            number_of_comparable_pairs+=1
            if score_difference*abundance_difference<0:
                number_of_inversions+=1

    if number_of_comparable_pairs>0:
        inversion_rate=number_of_inversions/number_of_comparable_pairs
        order_conservation_rate=1-inversion_rate
    else:
        inversion_rate=np.nan
        order_conservation_rate=np.nan

    # ─── Top-k recovery ────────────────────────────────────────────────────────────
    if np.array_equal(final_abundances,initial_abundances):
        current_top_k_indices=set(top_k_indices.tolist())
    else:
        finally_present_indices=np.flatnonzero((initial_abundances>0)&(final_abundances>0))
        if len(finally_present_indices)==0:
            current_top_k_indices=set()
        else:
            random_tie_break=np.random.random(len(finally_present_indices))
            local_abundance_order=np.lexsort((random_tie_break,-final_abundances[finally_present_indices]))
            abundance_order=finally_present_indices[local_abundance_order]
            current_top_k_indices=set(abundance_order[:k].tolist())
    number_recovered=len(set(top_k_indices.tolist())&current_top_k_indices)
    top_k_recovery=number_recovered/k
    return {
        "Kendall_tau":kendall_tau,
        "Spearman_rho":spearman_rho,
        "Inversion_rate":inversion_rate,
        "Order conservation rate":order_conservation_rate,
        f"Top-{k} recovery":top_k_recovery,
        "Number of recovered top-k sequences":number_recovered,
        "Number of inversions":number_of_inversions,
        "Number of comparable pairs":number_of_comparable_pairs,
        "Number of tied pairs":number_of_tied_pairs,
        "Number of compared sequences":k
    }

