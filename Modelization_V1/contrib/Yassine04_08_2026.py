def deterministic_sample(Lambda0,N1):
  """
  Parameters :
  Lambda0 : dict
    dictionnary containing all the sequences initially present
  Return :
  Lambda_prime : dict
    dictionnary containing all the sequences present after the deterministic sampling
  """
  N_0=sum(Lambda0.values())
  return { sequence : Lambda0[sequence]*(N1/N_0) for sequence in Lambda0.keys() }

