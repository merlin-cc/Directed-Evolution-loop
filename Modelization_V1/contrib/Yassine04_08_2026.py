# ─── Correct top-k recovery ──────────────────────────────────────────────────
def compute_top_k_recovery(library_object):
    """
    Compares the fixed combined-score top-k with the final-abundance top-k.

    Sequences with zero final abundance are excluded.
    """

    finally_present = [
        sequence
        for sequence in initial_sequences
        if library_object.Lambda[sequence] > 0
    ]

    if len(finally_present) == 0:
        return 0.0

    # Random tie-breaking independent of the theoretical score
    random_tie_break = {
        sequence: np.random.random()
        for sequence in finally_present
    }

    current_top_k = set(
        sorted(
            finally_present,
            key=lambda sequence: (
                library_object.Lambda[sequence],
                random_tie_break[sequence]
            ),
            reverse=True
        )[:k_heatmap]
    )

    number_recovered = len(
        reference_top_k
        & current_top_k
    )

    return number_recovered / k_heatmap


