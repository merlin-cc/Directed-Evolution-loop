"""### **Production of capsids**"""

def production_capside_per_sequence(s,nb_transfect_cells_s, alpha,T,F,J,epsilon=0.3):
  """
  Parameters:
  s : tuple
      Sequence
  alpha : float
      Baseline-mean production of capsids for a reference
  v : dict
      Viability score associated with sequence s
  T : float
      Temperature parameter controlling the strength of selection
  F : dict
      Score matrix
  J : float
      Interaction matrix
  epsilon : float
  Returns:
  nb_capsides : int
      Number of capsids produced by sequence s
  """
  score=fonction_score(s,F,J)
  mean_score=alpha*np.exp(score/T)

  nb_capsides=0
  for i in range(nb_transfect_cells_s):
    E_j=np.exp(epsilon*np.random.normal(loc=0, scale=1))
    nb_capsides+=np.random.poisson(alpha*E_j*mean_score)
  return nb_capsides

def production_capside_per_sequence(
    s,
    nb_transfect_cells_s,
    alpha,
    T,
    F,
    J,
    stoch=True,
    epsilon=0.3
):
    if nb_transfect_cells_s <= 0:
        return 0

    score = fonction_score(s,F,J)
    mean_number_capsides=alpha*np.exp(score/T)
    if stoch:
      E=np.exp(epsilon * np.random.normal(loc=0,scale=1,size=nb_transfect_cells_s))
      poisson_means=E*mean_number_capsides
      return int(np.random.poisson(poisson_means).sum())
    else :
      return int(mean_number_capsides*nb_transfect_cells_s)

