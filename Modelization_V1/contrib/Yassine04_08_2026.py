"""## **NGS Process**

We combine all the function we have defined above in order to make one function corresponding to a NGS
"""

def NGS(Lambda0, M, K_MM, D,N1):
  """
  Parameters:
  Lambda0 : dict
      Dictionnary containing the number of sequences s in the initial
  M : int
      Number of PCR cycles
  K_MM : float
      Michaelis–Menten constant
  D : int
      Sequencing depth
  N1 : int
    number of sequences we sample from Lambda0
  Returns:
  Lambda_prime : dict
      Dictionnary containing the number of reads of sequence s
  """
  Lambda=Lambda0.copy()
  Lambda=sample_sequences(Lambda, N1)
  Lambda=PCR_amplification(Lambda, M, K_MM)
  Lambda=sequencing(Lambda, D)
  return Lambda

