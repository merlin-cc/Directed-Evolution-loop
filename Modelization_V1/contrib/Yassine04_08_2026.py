"""## **Score function and production of capsids**

For a given sequence $s$, let

$$
P(s)
$$

be the total number of capsids produced from this sequence. We model it as

$$
P(s)=\sum_{i=1}^{T(s)} Z_{\sigma_s(i)}(s),
$$

where

$$
Z_{\sigma_s(i)}(s)
$$

denotes the number of capsids produced from sequence $s$ by the
$i$-th HEK cell transfected by this sequence.

We assume that

$$
Z_{\sigma_s(i)}(s)
\sim
\mathrm{Poisson}
\big(
\alpha\,E_{\sigma_s(i)}\,v(s)
\big),
$$

where

- $\alpha$ is the baseline mean production of capsids for a reference sequence;
- $E_{\sigma_s(i)}$ represents the efficiency of the HEK cell
$\sigma_s(i)$ relative to this baseline production;
- $v(s)$ is the viability score associated with sequence $s$.


Therefore, an average cell produces $\alpha$ capsids when the score of the sequence is not taken into account.

The viability score of sequence $s$ is defined by

$$
v(s)=\exp\!\left(\frac{\mathrm{score}(s)}{T}\right),
$$

where $T>0$ is a temperature parameter controlling the strength of selection.

Consequently, for any HEK cell $j$, we have

$$
\mathbb{E}[Z_j(s)\mid E_j]
=
\alpha
\times
E_j
\times
v(s).
$$

The expected number of capsids produced by a transfected cell is therefore the product of:

1. the reference mean production $\alpha$;
2. the efficiency of the cell $E_j$;
3. the viability score of the sequence $v(s)$.

Here we will consider that $$\alpha E_j(s)\approx \alpha e^{G_j} $$
with $G_j\sim\mathcal{N}(0,1)$

### Viability score with amino acid interactions

We define a sequence of amino acids as:

$$
s = a_1a_2 \cdots a_L
$$

where $L$ is the length of the sequence and $a_i$ is the amino acid at position $i$.

In the initial profile model, the viability score was computed as a simple sum of independent contributions:

$$
V(s)=\sum_{i=1}^{L} f_{i,\sigma(a_i)}
$$

where $f_{i,\sigma(a_i)}$ represents the contribution of amino acid $a_i$ at position $i$.

However, this model does not account for interactions between amino acids located at different positions. To include these effects, we introduce interaction matrices:

$$
J^{(i,i')} \in \mathbb{R}^{20 \times 20}
$$

for every pair of positions $(i,i')$ such that $1 \leq i < i' \leq L$.

The new viability score is then defined as:

$$
V'(s)
=
\sum_{i=1}^{L} f_{i,\sigma(a_i)}
+
\sum_{1 \leq i < i' \leq L}
J^{(i,i')}_{\sigma(a_i),\sigma(a_{i'})}$$

The first term corresponds to the individual effect of each amino acid, while the second term captures pairwise interactions between amino acids at different positions.

Thus, this extended model is more expressive than the initial profile model, because it can represent both independent positional effects and epistatic interactions between amino acids.
"""

def fonction_score(sequence,F,J) :
    """
    Calcule le score associé à une séquence.

    Paramètres
    ----------
    sequence : tuple
        sequence of lenght L
    F : np.array
        score matrix
    J : np.array
        interaction matrix
    Return
    ------
    score : float
        Score of the sequence.
    """
    L=len(sequence)
    score = 0
    for position_sequence in range(L):
        acide_amine=sequence[position_sequence]
        score += F[position_sequence][acide_amine-1]
        for position_sequence_bis in range(position_sequence):
            acide_amine_bis=sequence[position_sequence_bis]
            score+=J[position_sequence][position_sequence_bis][acide_amine-1][acide_amine_bis-1]
    return score

