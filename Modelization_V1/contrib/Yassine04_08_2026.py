"""## **PCR Amplification**
The sampled sequences then undergo $M$ cycles of PCR amplification. Following the model proposed, we denote by $X_s^{(n)}$ the number of copies of sequence $s$ after the $n-$th PCR cycle.

For each cycle $n \in \{1,\cdots,M-1\}$, the amplification dynamics are given by

$$
X_s^{(n+1)}
=
X_s^{(n)}
+
B\!\left(X_s^{(n)},p_n\right),
$$

where

$$
B\!\left(X_s^{(n)},p_n\right)
\sim
\mathrm{Binomial}\!\left(X_s^{(n)},p_n\right)
$$

represents the number of molecules of sequence \(s\) that are successfully copied during the \(n\)-th cycle.

The probability of replication at cycle \(n\) is assumed to follow a Michaelis–Menten law,

$$
p_n=
\left(
1+
\frac{\sum_{s'} X_{s'}^{(n)}}{K_{MM}}*texte en italique*
\right)^{-1},
$$

where $K_{MM}$ is the Michaelis–Menten constant.


"""

def amplification_step(Lambda, K_MM):
  """
  Parameters:
  Lambda : dict
      Dictionnary containing the number of sequences s in the sampled
  K_MM : float
      Michaelis
  Returns:
  Lambda_prime : dict
      Dictionnary containing the number of sequences s in the amplified
  """
  Lambda_prime=Lambda.copy()
  pn=(1+sum(Lambda.values())/K_MM)**(-1)
  for sequence in Lambda.keys():
      Lambda_prime[sequence]+=np.random.binomial(Lambda[sequence],pn)
  return Lambda_prime



def PCR_amplification(Lambda, M, K_MM):
  """
  Parameters:
  Lambda : dict
      Dictionnary containing the number of sequences s in the sampled
  M : int
      Number of PCR cycles
  K_MM : float
      Michaelis–Menten constant

  Returns:
  Lambda_prime : dict
      Dictionnary containing the number of sequences s in the amplified
  """
  Lambda_prime = Lambda.copy()
  for step in range(M):
    Lambda_prime=amplification_step(Lambda_prime, K_MM)
  return Lambda_prime

