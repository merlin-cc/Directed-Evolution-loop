# ============================================================

def estimate_F_OLS(
    Lambda_before,
    Lambda_after,
    L,
    T,
    pseudocount=0.5
):
    sequences = [
        sequence
        for sequence in Lambda_before
        if Lambda_before[sequence] > 0
    ]

    n_sequences = len(sequences)

    total_before = sum(Lambda_before.values())
    total_after = sum(Lambda_after.values())

    X = np.zeros(
        (n_sequences, 20 * L)
    )

    y = np.zeros(n_sequences)

    for sequence_index, sequence in enumerate(sequences):

        # One-hot encoding
        for position, amino_acid in enumerate(sequence):

            column = (
                20 * position
                + amino_acid
                - 1
            )

            X[sequence_index, column] = 1

        p_before = (
            Lambda_before[sequence]
            + pseudocount
        ) / (
            total_before
            + pseudocount * n_sequences
        )

        p_after = (
            Lambda_after.get(sequence, 0)
            + pseudocount
        ) / (
            total_after
            + pseudocount * n_sequences
        )

        y[sequence_index] = (
            T * np.log(
                p_after / p_before
            )
        )

    # Add the intercept
    X_design = np.column_stack([
        np.ones(n_sequences),
        X
    ])

    # OLS estimator: beta = X^+ y
    beta = (
        np.linalg.pinv(X_design)
        @ y
    )

    intercept = beta[0]

    # Convert the coefficient vector into an L x 20 matrix
    F_predicted = beta[1:].reshape(
        L,
        20
    )

    # Zero-mean gauge for each position
    F_predicted_centered = (
        F_predicted
        - F_predicted.mean(
            axis=1,
            keepdims=True
        )
    )

    y_predicted = X_design @ beta

    rmse = np.sqrt(
        np.mean(
            (y - y_predicted) ** 2
        )
    )

    ss_residual = np.sum(
        (y - y_predicted) ** 2
    )

    ss_total = np.sum(
        (y - y.mean()) ** 2
    )

    r2 = 1 - ss_residual / ss_total

    pearson = np.corrcoef(
        y,
        y_predicted
    )[0, 1]

    return {
        "F": F_predicted_centered,
        "intercept": intercept,
        "beta": beta,
        "X": X,
        "y": y,
        "y_predicted": y_predicted,
        "RMSE": rmse,
        "R2": r2,
        "Pearson": pearson
    }


