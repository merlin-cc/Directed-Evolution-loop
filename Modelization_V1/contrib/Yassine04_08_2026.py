    Lambda_prime=self.Lambda.copy()
    Lambda_prime=protocol_approx(Lambda_prime,self.alpha1,self.T1,self.rho,self.F1,self.J1,self.D,self.N1,self.epsilon)
    Lambda_prime=production_capside(Lambda_prime, self.alpha1,self.rho,self.F2,self.J2,self.T2,self.epsilon)
